"""Generate the frontend request contract from the deliberately simple Rust DTO file."""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src-tauri/src/models/requests.rs"
TARGET = ROOT / "src/api/contracts.ts"

def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()

def ts(kind):
    kind = kind.strip()
    if kind.startswith("Option<"):
        return ts(kind[7:-1]) + " | null"
    if kind.startswith("Vec<"):
        return f"Array<{ts(kind[4:-1])}>"
    return {"String": "string", "bool": "boolean", "u8": "number", "u16": "number", "u32": "number"}.get(kind, kind)

def fields(body):
    return " ".join(f"{name}: {ts(kind)};" for name, kind in re.findall(r"(?:pub )?(\w+): ([\w<>]+),", body))

def generate():
    source = SOURCE.read_text(encoding="utf-8")
    lines = ["// Generated by scripts/generate_types.py. Do not edit by hand.", "export type Int = string;"]
    for match in re.finditer(r"pub (struct|enum) (\w+) \{", source):
        level, end = 1, match.end()
        while level:
            level += (source[end] == "{") - (source[end] == "}")
            end += 1
        body = source[match.end():end-1]
        kind, name = match.groups()
        if kind == "struct":
            lines.append(f"export interface {name} {{ {fields(body)} }}")
        elif "{" in body:
            variants = [f"{{ type: '{snake(m.group(1))}'; {fields(m.group(2) or '')} }}" for m in re.finditer(r"(\w+)(?:\s*\{([^}]+)\})?\s*,", body)]
            lines.append(f"export type {name} =\n  " + " |\n  ".join(variants) + ";")
        else:
            lines.append(f"export type {name} = " + " | ".join(f"'{snake(v.strip())}'" for v in body.split(',') if v.strip()) + ";")
    return "\n".join(lines) + "\n"

content = generate()
if "--check" in sys.argv:
    if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != content:
        sys.exit("TypeScript contract is stale; run python3 scripts/generate_types.py")
else:
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(content, encoding="utf-8", newline="\n")
